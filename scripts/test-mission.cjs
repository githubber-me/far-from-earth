const assert=require('node:assert/strict');
const ts=require('typescript');
const fs=require('node:fs');
const vm=require('node:vm');
const code=ts.transpileModule(fs.readFileSync('src/lib/game/mission.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const sandbox={exports:{}};vm.runInNewContext(code,sandbox);
const {growCrop,stormDelta,missionStars}=sandbox.exports;
assert.equal(growCrop('tomatoes',2,4).food,9);
assert.equal(growCrop('tomatoes',3,4).watered,false);
assert.equal(growCrop('tomatoes',2,1).lit,false);
assert.equal(growCrop('potatoes',1,3).food,7);
const prep={alloc:{life:4,green:4,shield:4},water:'balanced',gearShielded:true};
const shield=stormDelta('shields',0,prep), plant=stormDelta('greenhouse',0,prep);
assert.ok(shield.dose<plant.dose);assert.ok(plant.food>shield.food);
assert.ok(stormDelta('shields',1,{...prep,alloc:{life:2,green:4,shield:6}}).dose<stormDelta('shields',1,prep).dose);
assert.ok(stormDelta('shields',0,{...prep,gearShielded:false}).dose>shield.dose);
assert.ok(stormDelta('shields',0,{...prep,water:'savers'}).o2>stormDelta('shields',0,{...prep,water:'comfort'}).o2);
assert.equal(missionStars({o2:60,dose:20,food:45,power:5}),3);
assert.equal(missionStars({o2:20,dose:80,food:10,power:0}),0);
console.log('11 checks passed: crop conditions, preparation effects, trade-offs, and outcome scoring.');
